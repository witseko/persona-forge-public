"""Codex outputs: `<name>.config.toml` files selected with `codex -p <name>`.

Each file sets only `developer_instructions`, layered by Codex on top of the user's
own config.toml, which this project never edits.
"""

from persona_forge.egos import Ego
from persona_forge.render_profile import render_ego_markdown


def toml_multiline_string(text: str) -> str:
    """Encode text as a TOML multi-line basic string.

    Backslashes and double quotes are escaped (so a run of three quotes can never end
    the string early), and control characters other than newline and tab become
    \\uXXXX escapes, as the TOML specification requires.
    """
    escaped = []
    for character in text:
        code = ord(character)
        if character == "\\":
            escaped.append("\\\\")
        elif character == '"':
            escaped.append('\\"')
        elif character in "\n\t":
            escaped.append(character)
        elif code < 0x20 or code == 0x7F:
            escaped.append(f"\\u{code:04X}")
        else:
            escaped.append(character)
    # A newline right after the opening delimiter is trimmed by TOML parsers.
    return '"""\n' + "".join(escaped) + '"""'


def render_codex_config(profile_markdown: str, ego: Ego | None = None) -> str:
    """Return a Codex profile file: the work profile, plus a persona when given."""
    instructions = profile_markdown
    if ego is not None:
        instructions += "\n" + render_ego_markdown(ego)
    if not instructions.strip():
        raise ValueError("developer_instructions cannot be blank")
    header = "# Generated by persona-forge. Regenerate with `make setup`; edits are overwritten.\n"
    return header + f"developer_instructions = {toml_multiline_string(instructions)}\n"


def codex_profile_name(ego: Ego | None) -> str:
    """Return the `-p` name: pf-me for the plain profile, pf-<ego> for a persona."""
    return "pf-me" if ego is None else f"pf-{ego.id}"
