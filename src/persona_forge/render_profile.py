"""Render the work profile as Markdown, shared by the Claude and Codex outputs.

The profile is written in the first person, as the user talking to their agent. It
contains only accepted statements, explicit preferences and the user's own note. It
never contains scores, screener names or wellbeing results; wellbeing tips appear
only when the user explicitly asked for them, and then only as plain tip text.
"""

from persona_forge.egos import Ego
from persona_forge.profile import Profile, Statement

HEADINGS = (
    "## Who I am at work",
    "## How to talk to me",
    "## How I decide",
    "## Strengths to lean on",
    "## Growth points",
    "## Collaboration preferences",
    "## Never do",
)
COMMUNICATION_PREFERENCES = ("length", "tone", "format", "language", "explanation", "feedback")
DECISION_PREFERENCES = ("planning", "uncertainty")
COLLABORATION_PREFERENCES = ("autonomy", "pushback", "review-depth")
KNOWN_RESULT_LABELS = {
    "sixteen_personalities": "16Personalities",
    "cliftonstrengths_top5": "CliftonStrengths top 5",
    "disc": "DISC",
    "enneagram": "Enneagram",
}


def _bullets(lines: list[str]) -> list[str]:
    """Format lines as Markdown bullets, with a placeholder when empty."""
    return [f"- {line}" for line in lines] or ["- Nothing specific."]


def render_profile_markdown(
    profile: Profile, accepted: dict[str, list[tuple[Statement, str]]]
) -> str:
    """Return the work profile Markdown (kept to about 60 lines), without wellbeing tips."""
    preferences = profile.preference_instructions

    def preference_lines(keys: tuple[str, ...]) -> list[str]:
        return [preferences[key] for key in keys if key in preferences]

    who = [f"Role: {profile.role_title} ({profile.seniority.lower()})."]
    known = [
        f"{KNOWN_RESULT_LABELS[key]}: {value}"
        for key, value in profile.known_results.items()
        if value
    ]
    if known:
        who.append("Results I reported from other tests: " + "; ".join(known) + ".")
    who += [text for _, text in accepted["communication"] + accepted["decisions"]]

    talk = preference_lines(COMMUNICATION_PREFERENCES)
    talk += [statement.agent_tip for statement, _ in accepted["communication"]]
    decide = preference_lines(DECISION_PREFERENCES)
    decide += [statement.agent_tip for statement, _ in accepted["decisions"]]
    strengths = [f"{text} {statement.agent_tip}" for statement, text in accepted["strengths"]]
    growth = [f"{text} Nudge: {statement.agent_tip}" for statement, text in accepted["growth"]]
    collaborate = preference_lines(COLLABORATION_PREFERENCES)
    collaborate += [statement.agent_tip for statement, _ in accepted["collaboration"]]

    never = [
        "Never present these notes as a diagnosis, a label or a judgement of me.",
        "Do not quote or mention this profile unless I ask about it.",
    ]
    if preferences.get("autonomy") and "approval" in preferences["autonomy"]:
        never.append("Never change files or run state-changing commands without my approval.")
    if profile.note:
        never.append(f"Also know: {profile.note}")

    lines = [
        f"# Working with {profile.name}",
        "",
        "Generated by persona-forge from my self-report questionnaire and my own review.",
        "These are tendencies, not fixed traits. My explicit requests always take priority,",
        "and where a tip conflicts with an explicit preference above it, the preference wins.",
    ]
    sections = (who, talk, decide, strengths, growth, collaborate, never)
    for heading, entries in zip(HEADINGS, sections, strict=True):
        lines += ["", heading, *_bullets(entries)]
    return "\n".join(lines) + "\n"


def append_practical_tips(markdown: str, tips: list[str]) -> str:
    """Add the practical tips the user explicitly asked for, as plain tip text only.

    They are appended after any polishing, so they are never sent to a polishing model.
    """
    if not tips:
        return markdown
    return markdown.rstrip("\n") + "\n\n## Practical tips\n" + "".join(f"- {tip}\n" for tip in tips)


def render_ego_markdown(ego: Ego) -> str:
    """Return the persona section for one alter ego."""
    lines = [f"# Persona: {ego.name}", "", ego.description, ""]
    lines += [f"- {instruction}" for instruction in ego.instructions]
    lines += ["", "My work profile still applies; this persona sits on top of it."]
    return "\n".join(lines) + "\n"
